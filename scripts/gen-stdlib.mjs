// Embed stdlib/*.moss into src/compiler/stdlib.generated.ts so the compiler
// has its standard library without a filesystem (e.g. in the browser).
// Run after editing anything in stdlib/ (npm test does it automatically).
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "stdlib");
const modules = {};
for (const f of readdirSync(dir).sort()) {
  if (!f.endsWith(".moss")) continue;
  const name = f[0].toUpperCase() + f.slice(1, -".moss".length);
  modules[name] = readFileSync(join(dir, f), "utf8");
}
const out = `// Generated by scripts/gen-stdlib.mjs from stdlib/*.moss. Do not edit.\n\nexport const STDLIB: Record<string, string> = ${JSON.stringify(modules, null, 2)};\n`;
writeFileSync(join(root, "src/compiler/stdlib.generated.ts"), out);
